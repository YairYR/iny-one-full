CREATE OR REPLACE FUNCTION security.is_domain_secure(domain_to_check text)
 RETURNS boolean
 LANGUAGE plpgsql
 SET search_path TO 'security'
AS $function$declare
  domain_found text;
  domain_is_custom bool;

BEGIN
  -- Check if the domain is in any blocked lists
  select
    domain into domain_found
  from security.cached_blocked_url
  where 
    domain = domain_to_check
  limit 1;

  if domain_found is not null then
    return false;
  end if;

  select
    domain into domain_found
  from security.whitelist_url
  where
    domain = domain_to_check
  limit 1;

  if domain_found is not null then
    return true;
  end if;

  select 
    domain,
    is_custom 
    into domain_found, 
    domain_is_custom
  from security.blocked_url
  where 
    domain = domain_to_check 
  limit 1;

  if domain_found is not null then
    insert into security.cached_blocked_url 
        (domain, is_custom) 
      values 
        (domain_to_check, domain_is_custom, domain_is_custom);
    return false;
  end if;

  select
    domain into domain_found
  from security.blocklist_url_phishing_active
  where
    domain = domain_to_check
  limit 1;

  if domain_found is not null then
    insert into security.cached_blocked_url 
        (domain, is_custom, is_permanent) 
      values 
        (domain_to_check, FALSE, FALSE);
    return false;
  end if;

  -- If the domain is not found in any list, cache it as allowed
  INSERT INTO security.whitelist_url (domain, is_custom)
  VALUES (domain_to_check, FALSE);

  return true;

END;$function$;
