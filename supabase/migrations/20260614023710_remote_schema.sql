CREATE OR REPLACE FUNCTION public.fn_log_audit()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_action text;
BEGIN
  -- Determinar el tipo de operación SQL
  IF (TG_OP = 'INSERT') THEN
    v_action := 'create';
  ELSIF (TG_OP = 'UPDATE') THEN
    v_action := 'update';
  ELSIF (TG_OP = 'DELETE') THEN
    v_action := 'delete';
  ELSE
    v_action := 'unknown';
  END IF;

  -- Insertar registro en audit_log
  INSERT INTO public.audit_logs (
    user_id,
    entity_type,
    entity_id,
    action,
    old_data,
    new_data
  )
  VALUES (
    -- Intentamos tomar el user_id del registro nuevo o viejo
    COALESCE(NEW.user_id, OLD.user_id),
    -- TG_ARGV[0] = argumento que le pasamos al crear el trigger (por ejemplo 'payment')
    TG_ARGV[0],
    -- ID del registro afectado (si es delete no hay NEW, si es insert no hay OLD)
    COALESCE(NEW.id, OLD.id),
    -- Acción detectada (create/update/delete)
    v_action,
    -- Guardamos los valores antiguos y nuevos para auditoría
    to_jsonb(OLD),
    to_jsonb(NEW)
  );

  -- Retornar NEW (necesario para triggers AFTER)
  RETURN NEW;
END;
$function$;
