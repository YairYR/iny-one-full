CREATE OR REPLACE FUNCTION public.get_dashboard_stats_summary(_slugs text[], _start_date timestamp without time zone, _end_date timestamp without time zone, _date_grouping text DEFAULT 'day'::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$DECLARE
  day_stats jsonb := '[]'::jsonb;
  top_countries jsonb := '[]'::jsonb;
  top_browsers jsonb := '[]'::jsonb;
  clicks_summary int8 := 0;
  clicks_all_time int8 := 0;
  clicks_last_24h int8 := 0;
BEGIN

  IF _date_grouping NOT IN ('day', 'week', 'month') THEN
    RAISE EXCEPTION 'Invalid date_grouping: %', _date_grouping
      USING ERRCODE = '22023';
  END IF;

  -- Agrega day stats
  SELECT coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) INTO day_stats
  FROM (
    SELECT
      date_trunc(_date_grouping, date)::date AS date,
      SUM(total_clicks) as clicks
    FROM public.short_links_daily_stats
    WHERE slug = ANY(_slugs) AND date >= _start_date::date AND date <= _end_date::date
    GROUP BY 1
    ORDER BY 1 ASC
  ) t;

  select count(*) into clicks_last_24h
  from public.history_clicks as h
  where 
  h.slug = ANY(_slugs)
  and h.created_at >= (CURRENT_TIMESTAMP - INTERVAL '1 day')
  and h.created_at <= CURRENT_TIMESTAMP;

  select count(*) into clicks_summary
  from public.history_clicks as h
  where 
  h.slug = ANY(_slugs)
  and h.created_at >= _start_date
  and h.created_at <= _end_date;

  SELECT 
    SUM(total_clicks::int) into clicks_all_time
  FROM public.short_links_stats t
  where slug = ANY(_slugs)
  LIMIT 1;

  SELECT coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) INTO top_countries
  FROM (
    SELECT 
      pairs.key as name,
      SUM(pairs.value::int) as value
    FROM public.short_links_stats t,
         jsonb_each_text(t.country_counts) pairs
    where slug = ANY(_slugs)
    GROUP BY pairs.key
    ORDER BY SUM(pairs.value::int) DESC
    LIMIT 3
  ) t;
  
  SELECT coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) INTO top_browsers
  FROM (
    SELECT 
      pairs.key as name,
      SUM(pairs.value::int) as value
    FROM public.short_links_stats t,
         jsonb_each_text(t.browser_counts) pairs
    where slug = ANY(_slugs)
    GROUP BY pairs.key
    ORDER BY SUM(pairs.value::int) DESC
    LIMIT 3
  ) t;

  return jsonb_build_object(
    'summary', jsonb_build_object(
      'clicks', clicks_summary,
      'clicks_last_24h', clicks_last_24h,
      'stats', day_stats,
      'date_start', _start_date,
      'date_end', _end_date,
      'date_grouping', _date_grouping
    ),
    'all_time', jsonb_build_object(
      'clicks', clicks_all_time,
      'top_countries', top_countries,
      'top_browsers', top_browsers
    )
  );
END;$function$;
