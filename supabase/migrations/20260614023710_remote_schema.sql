CREATE OR REPLACE FUNCTION public.authorize(requested_permission public.app_permission)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  bind_permissions int;
  user_role public.app_role;
begin
  -- Fetch user role once and store it to reduce number of calls
  select (auth.jwt() ->> 'user_role')::public.app_role into user_role;

  select count(*)
  into bind_permissions
  from public.role_permissions
  where role_permissions.permission = requested_permission
    and role_permissions.role = user_role;

  return bind_permissions > 0;
end;
$function$;
CREATE OR REPLACE FUNCTION public.click_short_link(page_slug text, user_ip text, user_country_code text, user_region text, user_city text, user_latitude text, user_longitude text, user_ua text, user_is_bot boolean, user_browser text, user_browser_version text, user_device_type text, user_device_vendor text, user_device_model text, user_os text, user_os_version text, user_referer text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$declare
  page_found text;
  page_domain text;
  page_utm_source text;
  page_utm_medium text;
  page_utm_campaign text;
  page_utm_content text;
  page_utm_term text;
  page_utm_id text;

BEGIN

SELECT 
  destination,
  domain,
  utm_source,
  utm_medium,
  utm_campaign,
  utm_content,
  utm_term,
  utm_id

  into page_found, 
  page_domain, 
  page_utm_source, 
  page_utm_medium,
  page_utm_campaign,
  page_utm_content,
  page_utm_term,
  page_utm_id
FROM public.short_links 
WHERE slug = page_slug;

if page_found is null then
  return;
end if;

UPDATE public.short_links
  SET clicks = clicks + 1
WHERE slug = page_slug;

INSERT INTO public.history_clicks (
  slug, ip, country_code, region, city, domain, 
  utm_source, utm_medium, utm_campaign, utm_content, utm_term, utm_id, 
  latitude, longitude, user_agent, is_bot, browser, browser_version, device_type, device_vendor, device_model, os, os_version, referer
) VALUES (
  page_slug, user_ip, user_country_code, user_region, user_city, page_domain, 
  page_utm_source, page_utm_medium, page_utm_campaign, page_utm_content, page_utm_term, page_utm_id, 
  user_latitude, user_longitude, user_ua, user_is_bot, user_browser, user_browser_version, user_device_type, user_device_vendor, user_device_model, user_os, user_os_version, user_referer
);

END;$function$;
